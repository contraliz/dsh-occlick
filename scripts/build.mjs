/**
 * Build `lib/client.js` from `src/client.js` and the sound library.
 *
 * The Web client serves exactly one script per plugin row, so every clip is
 * embedded in that script as a data URI. `assets/audio` holds the originals;
 * running this script is the only step that reads them.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const audioDir = join(root, 'assets', 'audio');
const sourcePath = join(root, 'src', 'client.js');
const outputPath = join(root, 'lib', 'client.js');
const placeholder = '__SOUND_LIBRARY__';

/**
 * Turn a sound id into the label OpenCode shows in its own picker.
 * @param id - file stem such as `bip-bop-06`.
 * @returns the display label, `Bip-bop 06`.
 */
function labelOf(id) {
  const stem = id.replace(/\.mp3$/, '');
  const cut = stem.lastIndexOf('-');
  if (cut < 0) return stem.charAt(0).toUpperCase() + stem.slice(1);
  const family = stem.slice(0, cut);
  const number = stem.slice(cut + 1);
  return `${family.charAt(0).toUpperCase()}${family.slice(1)} ${number}`;
}

const files = readdirSync(audioDir)
  .filter((name) => name.endsWith('.mp3'))
  .sort((left, right) => left.localeCompare(right));

if (files.length === 0) {
  console.error(`No sounds found in ${audioDir}. Run scripts/fetch-sounds.mjs first.`);
  process.exit(1);
}

const library = files.map((file) => {
  const id = file.replace(/\.mp3$/, '');
  const bytes = readFileSync(join(audioDir, file));
  return { id, label: labelOf(id), data: `data:audio/mpeg;base64,${bytes.toString('base64')}` };
});

const source = readFileSync(sourcePath, 'utf8');
if (!source.includes(placeholder)) {
  console.error(`src/client.js does not contain ${placeholder}`);
  process.exit(1);
}

const banner = `// dsh-occlick — generated by scripts/build.mjs. Edit src/client.js instead.\n`;
const built = banner + source.replace(placeholder, JSON.stringify(library));

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, built);

const kb = (size) => `${(size / 1024).toFixed(0)} KB`;
console.log(`built lib/client.js with ${library.length} sounds, ${kb(Buffer.byteLength(built))}`);
